export function presentationEnabled(
  env: Record<string, string | undefined>,
  path: string,
) {
  if (env.DITTO_PRESENTATION_FIXTURES !== "1") return false;
  // Explicit local-only opt-in and a dedicated filename; never seed a linked deployment.
  if (
    !/ditto-presentation[^/]*\.sqlite$/.test(path) ||
    env.RAILWAY_ENVIRONMENT_ID ||
    env.VERCEL ||
    (env.PUBLIC_ORIGIN &&
      !/^http:\/\/(localhost|127\.0\.0\.1)(:\d+)?$/.test(env.PUBLIC_ORIGIN))
  ) {
    throw new Error(
      "Presentation fixtures require a dedicated ditto-presentation*.sqlite database and a local environment.",
    );
  }
  return true;
}
